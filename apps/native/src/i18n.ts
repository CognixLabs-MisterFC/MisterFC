const LOCALE: Locale = detectLocale();

export function t(key: string, vars?: Record<string, string>): string {
  let msg = MESSAGES[LOCALE][key] ?? MESSAGES.es[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      msg = msg.replace(`{${k}}`, v);
    }
  }
  return msg;
}
